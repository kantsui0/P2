import assert from 'node:assert/strict'
import { clientTotal, clientBadge, topClients, dashboardMetrics, filterOrders } from '../src/utils/metrics.ts'
const order = (id, clienteId, status, value, data='2026-11-17') => Object.freeze({ id, clienteId, status, data, itens: Object.freeze([Object.freeze({titulo:'Teste',preco:value,quantidade:1})]) })
const base=Object.freeze([order(1,1,'aberto',1500),order(2,1,'pago',500),order(3,1,'cancelado',9000)])
assert.equal(clientTotal(base,1),2000); assert.equal(clientBadge(base,1),'VIP')
assert.deepEqual(dashboardMetrics(base),{total:2000,average:1000,statuses:[{status:'aberto',count:1,total:1500},{status:'pago',count:1,total:500},{status:'cancelado',count:1,total:9000}]})
const canceled=Object.freeze(base.map(o=>o.id===1?order(1,1,'cancelado',1500):o))
assert.equal(clientTotal(canceled,1),500); assert.equal(clientBadge(canceled,1),'Regular')
assert.equal(clientBadge([order(1,1,'pago',0)],1),'Regular')
assert.equal(clientBadge([order(1,1,'cancelado',9000)],1),'Sem compras')
assert.equal(dashboardMetrics([order(1,1,'pago',500),order(2,1,'aberto',0)]).average,250)
assert.deepEqual(filterOrders([order(1,1,'aberto',0)],'',0,0,'total-asc').map(o=>o.id),[1])
assert.equal(clientBadge([],1),'Sem compras');assert.equal(dashboardMetrics([]).average,0)
assert.equal(dashboardMetrics([order(1,1,'cancelado',9000)]).average,0)
assert.equal(clientBadge([order(1,1,'aberto',1999.99)],1),'Regular')
const ranked=Object.freeze([...base,order(4,2,'pago',3000),order(5,3,'aberto',1000)])
const clients=Object.freeze([Object.freeze({id:1,nome:'A'}),Object.freeze({id:2,nome:'B'}),Object.freeze({id:3,nome:'C'})])
assert.deepEqual(topClients(clients,ranked).map(c=>[c.nome,c.total]),[['B',3000],['A',2000],['C',1000]])
assert.deepEqual(filterOrders(ranked,'aberto',1000,1500,'total-desc').map(o=>o.id),[1,5])
assert.deepEqual(filterOrders(ranked,'cancelado',9000,9000,'date-desc').map(o=>o.id),[3])
assert.deepEqual(filterOrders([order(1,1,'aberto',100,'2026-01-02'),order(2,1,'aberto',10,'2025-12-31')],'',null,null,'date-asc').map(o=>o.id),[2,1])
assert.deepEqual(base.map(o=>o.id),[1,2,3])
console.log('PASS: totais/selos/VIP limite/zero válido/sem válidos/média zero/status/Top3/filtros inclusivos/ordenação; entradas congeladas sem mutação.')
